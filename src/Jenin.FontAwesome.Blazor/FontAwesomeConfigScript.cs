namespace Jenin.FontAwesome.Blazor;

/// <summary>
/// Single source of truth for the Font Awesome mode-config scripts: the two static files under
/// <c>wwwroot/js</c> (<c>fontawesome-config-nest.js</c>, <c>fontawesome-config-webfont.js</c>)
/// and the generated endpoint served by <c>MapJeninFontAwesomeAssets</c> share these payloads.
/// </summary>
/// <remarks>
/// Every payload sets only <c>autoReplaceSvg</c>, preserving unrelated
/// <c>window.FontAwesomeConfig</c> entries the host already defined. Non-destructive and
/// idempotent; safe under duplicate inclusion. Must load before the Font Awesome runtime.
/// </remarks>
internal static class FontAwesomeConfigScript {
    internal const string SVG_NEST_PAYLOAD = "window.FontAwesomeConfig = Object.assign({}, window.FontAwesomeConfig, { autoReplaceSvg: \"nest\" });";
    internal const string WEBFONT_PAYLOAD = "window.FontAwesomeConfig = Object.assign({}, window.FontAwesomeConfig, { autoReplaceSvg: false });";

    internal static string GetScript(FontAwesomeAssetMode mode) {
        var payload = mode == FontAwesomeAssetMode.Webfont ? WEBFONT_PAYLOAD : SVG_NEST_PAYLOAD;

        return "\"use strict\";\n"
            + "// Generated by Jenin.FontAwesome.Blazor (MapJeninFontAwesomeAssets) for "
            + (mode == FontAwesomeAssetMode.Webfont ? "webfont" : "SVG-nest")
            + " mode. Keep in sync with wwwroot/js/fontawesome-config-*.js.\n"
            + payload
            + "\n";
    }
}
