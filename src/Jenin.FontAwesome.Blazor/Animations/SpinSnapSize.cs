namespace Jenin.FontAwesome.Blazor.Animations;

/// <summary>
/// Specifies the number of discrete steps used by a <see cref="SpinSnap"/> rotation.
/// </summary>
public enum SpinSnapSize {
    /// <summary>Continuous snap rotation (<c>fa-spin-snap</c>).</summary>
    Default = 0,

    /// <summary>Four-step snap rotation (<c>fa-spin-snap-4</c>).</summary>
    Four = 4,

    /// <summary>Eight-step snap rotation (<c>fa-spin-snap-8</c>).</summary>
    Eight = 8,
}
