#!/usr/bin/env pwsh
<#
.SYNOPSIS
    Generates the strongly-typed Font Awesome icon-name catalogue source file.
.DESCRIPTION
    Reads the vendored compact metadata produced by `eng/update-fontawesome-metadata.ps1` and emits
    `IconNames.cs`: a public static class exposing every Free icon name as a compile-time constant,
    grouped into nested `Solid`, `Regular`, and `Brands` classes.

    The generator is deterministic (ordinal ordering), reports identifier collisions as errors, and supports
    a `-Verify` mode used by CI to fail when the committed file drifts from the metadata.
.PARAMETER MetadataPath
    The vendored compact metadata file. Defaults to `eng/metadata/fontawesome-7.3.1-free-icons.json`.
.PARAMETER OutputPath
    The generated source file. Defaults to `src/Jenin.FontAwesome.Blazor/IconNames.cs`.
.PARAMETER Verify
    When set, performs no writes and exits with a non-zero code if the committed file differs from the
    freshly generated output.
.EXAMPLE
    pwsh ./eng/generate-icon-catalogue.ps1
    pwsh ./eng/generate-icon-catalogue.ps1 -Verify
#>
[CmdletBinding()]
param(
    [string] $MetadataPath,
    [string] $OutputPath,
    [switch] $Verify
)

$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot

if(-not $MetadataPath) {
    $MetadataPath = Join-Path $root 'eng/metadata/fontawesome-7.3.1-free-icons.json'
}

if(-not $OutputPath) {
    $OutputPath = Join-Path $root 'src/Jenin.FontAwesome.Blazor/IconNames.cs'
}

function ConvertTo-Identifier {
    param([string] $Name)

    $builder = [System.Text.StringBuilder]::new()

    foreach($part in ($Name -split '[-_]')) {
        if($part.Length -eq 0) {
            continue
        }

        [void]$builder.Append([char]::ToUpperInvariant($part[0]))

        if($part.Length -gt 1) {
            [void]$builder.Append($part.Substring(1))
        }
    }

    $identifier = $builder.ToString()

    if($identifier.Length -gt 0 -and [char]::IsDigit($identifier[0])) {
        $identifier = '_' + $identifier
    }

    return $identifier
}

$metadata = Get-Content -LiteralPath $MetadataPath -Raw | ConvertFrom-Json -AsHashtable
$version = $metadata.version

$styles = @(
    [pscustomobject]@{ Class = 'Solid';   Key = 'solid';   CssClass = 'fa-solid' },
    [pscustomobject]@{ Class = 'Regular'; Key = 'regular'; CssClass = 'fa-regular' },
    [pscustomobject]@{ Class = 'Brands';  Key = 'brands';  CssClass = 'fa-brands' }
)

$lines = [System.Collections.Generic.List[string]]::new()

foreach($headerLine in @(
    '//',
    '// Copyright (c) Jeninnet.',
    '// Part of the Jeninnet Platform.',
    '// Repository: https://github.com/TarekNajem04/Jenin.FontAwesome.Blazor/',
    '// Licensed under the MIT License.',
    '//',
    '// <auto-generated>',
    "//   Generated by eng/generate-icon-catalogue.ps1 from Font Awesome Free $version metadata.",
    "//   Source: $($metadata.source)",
    '//   Do not edit this file by hand. Regenerate with: pwsh ./eng/generate-icon-catalogue.ps1',
    '// </auto-generated>'
)) {
    $lines.Add($headerLine)
}

$lines.Add('')
$lines.Add('#pragma warning disable CS0108 // Icon names may match System.Object member names (for example, the "equals" icon).')
$lines.Add('')
$lines.Add('namespace Jenin.FontAwesome.Blazor;')
$lines.Add('')
$lines.Add('/// <summary>')
$lines.Add("/// Strongly-typed catalogue of Font Awesome Free $version canonical icon names, grouped by the style")
$lines.Add('/// in which each name is available. Assign a constant to <c>Icon.IconName</c> for compile-time')
$lines.Add('/// checking and IntelliSense (for example, <c>IconNames.Solid.House</c>).')
$lines.Add('/// </summary>')
$lines.Add('/// <remarks>')
$lines.Add('/// Names describe the style-independent <c>fa-</c> prefixed identifier; combine a constant with the')
$lines.Add('/// matching <c>IconStyle</c> to select the desired style. Only Font Awesome Free styles are listed.')
$lines.Add('/// </remarks>')
$lines.Add('public static class IconNames {')

for($index = 0; $index -lt $styles.Count; $index++) {
    $style = $styles[$index]
    $names = @($metadata.styles[$style.Key])

    $identifiers = [System.Collections.Generic.SortedDictionary[string, string]]::new([System.StringComparer]::Ordinal)

    foreach($name in $names) {
        $identifier = ConvertTo-Identifier -Name $name

        if($identifiers.ContainsKey($identifier)) {
            throw "Identifier collision in style '$($style.Class)': '$identifier' is produced by both '$($identifiers[$identifier])' and '$name'. Extend ConvertTo-Identifier to disambiguate."
        }

        $identifiers[$identifier] = "fa-$name"
    }

    $lines.Add("    /// <summary>Font Awesome $($style.Class) style (<c>$($style.CssClass)</c>, $($identifiers.Count) icons).</summary>")
    $lines.Add("    public static class $($style.Class) {")

    foreach($entry in $identifiers.GetEnumerator()) {
        $lines.Add("        /// <summary>The <c>$($entry.Value)</c> Font Awesome icon name ($($style.Class) style).</summary>")
        $lines.Add("        public const string $($entry.Key) = `"$($entry.Value)`";")
    }

    $lines.Add('    }')

    if($index -lt ($styles.Count - 1)) {
        $lines.Add('')
    }
}

$lines.Add('}')

$content = ($lines -join "`r`n") + "`r`n"

if($Verify) {
    if(-not (Test-Path -LiteralPath $OutputPath)) {
        Write-Host "Missing generated icon catalogue: $OutputPath"
        exit 1
    }

    $existing = [System.IO.File]::ReadAllText($OutputPath)

    if($existing -ne $content) {
        Write-Host 'The icon catalogue is out of date. Run: pwsh ./eng/generate-icon-catalogue.ps1'
        exit 1
    }

    Write-Host 'Icon catalogue is up to date.'
    exit 0
}

[System.IO.File]::WriteAllText($OutputPath, $content, (New-Object System.Text.UTF8Encoding($true)))

$counts = foreach($style in $styles) {
    '{0}={1}' -f $style.Class, (@($metadata.styles[$style.Key]).Count)
}

Write-Host "Wrote $OutputPath (Font Awesome $version; $($counts -join ', '))"
