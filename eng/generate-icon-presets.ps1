#!/usr/bin/env pwsh
<#
.SYNOPSIS
    Generates the per-icon preset components for the Jenin.FontAwesome.Blazor.Icons package.
.DESCRIPTION
    Reads the rich per-icon metadata vendored by `eng/update-fontawesome-metadata.ps1` and emits
    `GeneratedIconComponents.cs`: one public component per unique Font Awesome Free icon that derives
    from `Icon`, bakes the icon name in, and defaults to the icon's primary style.

    The generator is deterministic (icons in ordinal name order, fixed formatting), reports identifier
    collisions as errors, and supports a `-Verify` mode used by CI to fail when the committed file drifts
    from the vendored metadata.
.PARAMETER MetadataPath
    The vendored rich metadata file. Defaults to `eng/metadata/fontawesome-7.3.1-free-icon-metadata.json`.
.PARAMETER OutputPath
    The generated source file. Defaults to
    `src/Jenin.FontAwesome.Blazor.Icons/GeneratedIconComponents.cs`.
.PARAMETER Verify
    When set, performs no writes and exits with a non-zero code if the committed file differs from the
    freshly generated output.
.EXAMPLE
    pwsh ./eng/generate-icon-presets.ps1
    pwsh ./eng/generate-icon-presets.ps1 -Verify
#>
[CmdletBinding()]
param(
    [string] $MetadataPath,
    [string] $OutputPath,
    [switch] $Verify
)

$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot

if(-not $MetadataPath) {
    $MetadataPath = Join-Path $root 'eng/metadata/fontawesome-7.3.1-free-icon-metadata.json'
}

if(-not $OutputPath) {
    $OutputPath = Join-Path $root 'src/Jenin.FontAwesome.Blazor.Icons/GeneratedIconComponents.cs'
}

function ConvertTo-Identifier {
    param([string] $Name)

    $builder = [System.Text.StringBuilder]::new()

    foreach($part in ($Name -split '[-_]')) {
        if($part.Length -eq 0) {
            continue
        }

        [void]$builder.Append([char]::ToUpperInvariant($part[0]))

        if($part.Length -gt 1) {
            [void]$builder.Append($part.Substring(1))
        }
    }

    $identifier = $builder.ToString()

    if($identifier.Length -gt 0 -and [char]::IsDigit($identifier[0])) {
        $identifier = '_' + $identifier
    }

    return $identifier
}

function Get-PrimaryStyle {
    param([object[]] $Styles)

    if($Styles -contains 'solid') {
        return 'Solid'
    }

    if($Styles -contains 'regular') {
        return 'Regular'
    }

    if($Styles -contains 'brands') {
        return 'Brands'
    }

    return 'Solid'
}

function ConvertTo-XmlText {
    param([string] $Value)

    return [System.Security.SecurityElement]::Escape($Value)
}

$metadata = Get-Content -LiteralPath $MetadataPath -Raw | ConvertFrom-Json -AsHashtable
$version = $metadata.version

$icons = [System.Collections.Generic.SortedDictionary[string, object]]::new([System.StringComparer]::Ordinal)
$components = [System.Collections.Generic.Dictionary[string, string]]::new([System.StringComparer]::Ordinal)

foreach($icon in @($metadata.icons)) {
    $name = [string]$icon.name
    $label = if($icon.label) { [string]$icon.label } else { $name }
    $style = Get-PrimaryStyle -Styles @($icon.styles)
    $identifier = ConvertTo-Identifier -Name $name
    $component = $identifier + 'Icon'

    if($components.ContainsKey($component)) {
        throw "Component collision: '$component' is produced by both '$($components[$component])' and '$name'."
    }

    $components[$component] = $name

    $icons[$name] = [pscustomobject]@{
        Name      = $name
        Label     = $label
        CssClass  = "fa-$name"
        Style     = $style
        Component = $component
    }
}

$lines = [System.Collections.Generic.List[string]]::new()

foreach($headerLine in @(
    '//',
    '// Copyright (c) Jeninnet.',
    '// Part of the Jeninnet Platform.',
    '// Repository: https://github.com/TarekNajem04/Jenin.FontAwesome.Blazor/',
    '// Licensed under the MIT License.',
    '//',
    '// <auto-generated>',
    "//   Generated by eng/generate-icon-presets.ps1 from Font Awesome Free $version metadata.",
    "//   Source: $($metadata.source)",
    '//   Do not edit this file by hand. Regenerate with: pwsh ./eng/generate-icon-presets.ps1',
    '// </auto-generated>'
)) {
    $lines.Add($headerLine)
}

$lines.Add('')
$lines.Add('namespace Jenin.FontAwesome.Blazor.Icons;')
$lines.Add('')
$lines.Add('// Per-icon preset components for the Font Awesome Free catalogue. Each component derives from')
$lines.Add('// Icon, bakes the icon name in, and defaults to the icon''s primary Free style. Every style,')
$lines.Add('// transformation, animation, and accessibility parameter remains overridable.')

foreach($entry in $icons.Values) {
    $label = ConvertTo-XmlText -Value $entry.Label

    $lines.Add('')
    $lines.Add("/// <summary>The Font Awesome <c>$($entry.CssClass)</c> icon (<c>fa-$($entry.Style.ToLowerInvariant())</c>; $label).</summary>")
    $lines.Add("public class $($entry.Component) : Icon {")
    $lines.Add("    /// <summary>Creates a Font Awesome <c>$($entry.CssClass)</c> icon preset.</summary>")
    $lines.Add("    public $($entry.Component)() {")
    $lines.Add("        IconName = `"$($entry.CssClass)`";")
    $lines.Add("        IconStyle = IconStyle.$($entry.Style);")
    $lines.Add('    }')
    $lines.Add('}')
}

$content = ($lines -join "`r`n") + "`r`n"

if($Verify) {
    if(-not (Test-Path -LiteralPath $OutputPath)) {
        Write-Host "Missing generated icon presets: $OutputPath"
        exit 1
    }

    $existing = [System.IO.File]::ReadAllText($OutputPath)

    if($existing -ne $content) {
        Write-Host 'The generated icon presets are out of date. Run: pwsh ./eng/generate-icon-presets.ps1'
        exit 1
    }

    Write-Host 'Generated icon presets are up to date.'
    exit 0
}

$outputDirectory = Split-Path -Parent $OutputPath

if(-not (Test-Path -LiteralPath $outputDirectory)) {
    New-Item -ItemType Directory -Path $outputDirectory -Force | Out-Null
}

[System.IO.File]::WriteAllText($OutputPath, $content, (New-Object System.Text.UTF8Encoding($true)))

Write-Host "Wrote $OutputPath (Font Awesome $version; $($icons.Count) components)"
