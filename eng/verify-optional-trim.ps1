#!/usr/bin/env pwsh
#
# Publish-level trimming verification for the optional packages.
#
# Publishes three disposable probe executables with IL trimming fully enabled and asserts the
# trim/AOT contracts at PUBLISH level instead of relying on build-time analyzers alone:
#
#   * IconPicker probe  - runs the embedded-metadata pipeline end to end (manifest-resource load,
#     JSON parse, ranked search) inside a fully trimmed output, proving the metadata contract
#     remains loadable after the linker has run.
#   * Icons probe - proves a referenced generated preset component is retained by the linker and
#     that an unreferenced preset is removed from the published assembly, documenting the expected
#     retention/removal behavior for consumers shipping trimmed Blazor apps.
#   * Svg probe - proves a referenced generated inline-SVG component is retained by the linker
#     and that an unreferenced one is removed from the published assembly, documenting the same
#     contract for the self-contained SVG package.
#
# The probes are standalone executables because a trimmed publish of a console host is the only
# hosting model that can be published and executed headlessly on every supported TFM. Blazor
# WebAssembly consumers additionally trim by construction, and CI's sample gate publishes the docs
# sample (a WASM host that transitively references the optional packages) trimmed. Server-side
# `PublishTrimmed` is not officially supported by the shared ASP.NET Core framework and is
# deliberately not claimed (see the README).
#
# Probes are generated under artifacts/ (outside the governed source roots) and removed afterwards.
#
# Usage:
#   pwsh ./eng/verify-optional-trim.ps1
#   pwsh ./eng/verify-optional-trim.ps1 -Configuration Debug
#   pwsh ./eng/verify-optional-trim.ps1 -Tfms net10.0

[CmdletBinding()]
param(
    [string]$Configuration = 'Release',
    [string[]]$Tfms = @('net8.0', 'net9.0', 'net10.0')
)

$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$probeRoot = Join-Path $root 'artifacts' 'optional-trim-probe'

$iconPickerCsproj = (Resolve-Path (Join-Path $root 'src' 'Jenin.FontAwesome.Blazor.IconPicker' 'Jenin.FontAwesome.Blazor.IconPicker.csproj')).Path
$iconsCsproj = (Resolve-Path (Join-Path $root 'src' 'Jenin.FontAwesome.Blazor.Icons' 'Jenin.FontAwesome.Blazor.Icons.csproj')).Path
$svgCsproj = (Resolve-Path (Join-Path $root 'src' 'Jenin.FontAwesome.Blazor.Svg' 'Jenin.FontAwesome.Blazor.Svg.csproj')).Path

$iconPickerProgram = @'
//
// Generated by eng/verify-optional-trim.ps1. Disposable trimming probe; do not edit by hand.
//
using System;
using Jenin.FontAwesome.Blazor;
using Jenin.FontAwesome.Blazor.IconPicker;

var provider = IconMetadataProvider.Default;
var house = provider.Find("fa-house");
var arrows = provider.Search("arrow", IconStyle.Solid, 5);

Console.WriteLine($"icons={provider.Icons.Count} house={house?.Name ?? "<none>"} arrows={arrows.Count}");

var ok = house is not null
    && string.Equals(house.Name, "house", StringComparison.Ordinal)
    && house.SupportsStyle(IconStyle.Solid)
    && arrows.Count > 0
    && provider.Icons.Count >= 1900;

Environment.Exit(ok ? 0 : 3);
'@

$iconsProgram = @'
//
// Generated by eng/verify-optional-trim.ps1. Disposable trimming probe; do not edit by hand.
//
using System;
using System.IO;
using System.Text;
using Jenin.FontAwesome.Blazor.Icons;

var referenced = new HouseIcon();

var assemblyPath = Path.Combine(AppContext.BaseDirectory, "Jenin.FontAwesome.Blazor.Icons.dll");
var bytes = File.ReadAllBytes(assemblyPath);
var houseRetained = IndexOfUtf8(bytes, "HouseIcon") >= 0;
var lightbulbRemoved = IndexOfUtf8(bytes, "LightbulbIcon") < 0;

Console.WriteLine($"referenced-name={referenced.IconName} house-retained={houseRetained} lightbulb-removed={lightbulbRemoved}");

var ok = string.Equals(referenced.IconName, "fa-house", StringComparison.Ordinal)
    && houseRetained
    && lightbulbRemoved;

Environment.Exit(ok ? 0 : 3);

static int IndexOfUtf8(byte[] haystack, string needle) {
    var pattern = Encoding.UTF8.GetBytes(needle);

    for(var i = 0; i + pattern.Length <= haystack.Length; i++) {
        var matched = true;

        for(var j = 0; j < pattern.Length; j++) {
            if(haystack[i + j] != pattern[j]) {
                matched = false;
                break;
            }
        }

        if(matched) {
            return i;
        }
    }

    return -1;
}
'@

$probeCsproj = @'
<Project Sdk="Microsoft.NET.Sdk">

    <PropertyGroup>
        <OutputType>Exe</OutputType>
        <AssemblyName>OptionalTrimProbe</AssemblyName>
        <RootNamespace>OptionalTrimProbe</RootNamespace>
        <TargetFramework>{0}</TargetFramework>
        <PublishTrimmed>true</PublishTrimmed>
        <TrimMode>full</TrimMode>
        <InvariantGlobalization>true</InvariantGlobalization>
        <GenerateDocumentationFile>false</GenerateDocumentationFile>
    </PropertyGroup>

    <ItemGroup>
        <ProjectReference Include="{1}" />
    </ItemGroup>

</Project>
'@

$svgProgram = @'
// Generated by eng/verify-optional-trim.ps1. Disposable trimming probe; do not edit by hand.
//
using System;
using System.IO;
using System.Text;
using Jenin.FontAwesome.Blazor.Svg;

var referenced = new HouseSolidIcon();

var assemblyPath = Path.Combine(AppContext.BaseDirectory, "Jenin.FontAwesome.Blazor.Svg.dll");
var bytes = File.ReadAllBytes(assemblyPath);
var houseRetained = IndexOfUtf8(bytes, "HouseSolidIcon") >= 0;
var githubRemoved = IndexOfUtf8(bytes, "GithubBrandsIcon") < 0;

Console.WriteLine($"referenced-type={referenced.GetType().Name} house-retained={houseRetained} github-removed={githubRemoved}");

var ok = string.Equals(referenced.GetType().Name, "HouseSolidIcon", StringComparison.Ordinal)
    && houseRetained
    && githubRemoved;

Environment.Exit(ok ? 0 : 3);

static int IndexOfUtf8(byte[] haystack, string needle) {
    var pattern = Encoding.UTF8.GetBytes(needle);

    for(var i = 0; i + pattern.Length <= haystack.Length; i++) {
        var matched = true;

        for(var j = 0; j < pattern.Length; j++) {
            if(haystack[i + j] != pattern[j]) {
                matched = false;
                break;
            }
        }

        if(matched) {
            return i;
        }
    }

    return -1;
}
'@

function New-TfmProbe {
    param(
        [string]$Name,
        [string]$Tfm,
        [string]$ProjectReference,
        [string]$Program
    )

    $probeDir = Join-Path $probeRoot $Name $Tfm
    New-Item -ItemType Directory -Force -Path $probeDir | Out-Null

    $probeCsprojContent = $probeCsproj -f $Tfm, $ProjectReference

    [System.IO.File]::WriteAllText(
        (Join-Path $probeDir 'OptionalTrimProbe.csproj'),
        $probeCsprojContent)

    [System.IO.File]::WriteAllText((Join-Path $probeDir 'Program.cs'), $Program)

    return $probeDir
}

if(Test-Path -LiteralPath $probeRoot) {
    Remove-Item -Recurse -Force -Path $probeRoot
}

foreach($tfm in $Tfms) {
    Write-Host "==> Optional-package trimming probes ($tfm)" -ForegroundColor Cyan

    $iconPickerProbeDir = New-TfmProbe -Name 'IconPicker' -Tfm $tfm -ProjectReference $iconPickerCsproj -Program $iconPickerProgram
    $iconsProbeDir = New-TfmProbe -Name 'Icons' -Tfm $tfm -ProjectReference $iconsCsproj -Program $iconsProgram
    $svgProbeDir = New-TfmProbe -Name 'Svg' -Tfm $tfm -ProjectReference $svgCsproj -Program $svgProgram

    $iconPickerPublishDir = Join-Path $iconPickerProbeDir 'publish'
    $iconsPublishDir = Join-Path $iconsProbeDir 'publish'
    $svgPublishDir = Join-Path $svgProbeDir 'publish'

    dotnet publish (Join-Path $iconPickerProbeDir 'OptionalTrimProbe.csproj') -c $Configuration -o $iconPickerPublishDir --nologo
    if($LASTEXITCODE -ne 0) { throw "IconPicker probe publish failed for $tfm." }

    dotnet publish (Join-Path $iconsProbeDir 'OptionalTrimProbe.csproj') -c $Configuration -o $iconsPublishDir --nologo
    if($LASTEXITCODE -ne 0) { throw "Icons probe publish failed for $tfm." }

    dotnet publish (Join-Path $svgProbeDir 'OptionalTrimProbe.csproj') -c $Configuration -o $svgPublishDir --nologo
    if($LASTEXITCODE -ne 0) { throw "Svg probe publish failed for $tfm." }

    dotnet (Join-Path $iconPickerPublishDir 'OptionalTrimProbe.dll')
    if($LASTEXITCODE -ne 0) { throw "IconPicker probe FAILED for $tfm (embedded metadata broken after trimming)." }

    dotnet (Join-Path $iconsPublishDir 'OptionalTrimProbe.dll')
    if($LASTEXITCODE -ne 0) { throw "Icons probe FAILED for $tfm (retention/removal contract violated)." }

    dotnet (Join-Path $svgPublishDir 'OptionalTrimProbe.dll')
    if($LASTEXITCODE -ne 0) { throw "Svg probe FAILED for $tfm (retention/removal contract violated)." }

    $iconPickerDll = (Get-Item (Join-Path $iconPickerPublishDir 'Jenin.FontAwesome.Blazor.IconPicker.dll')).Length
    $iconsDll = (Get-Item (Join-Path $iconsPublishDir 'Jenin.FontAwesome.Blazor.Icons.dll')).Length
    $svgDll = (Get-Item (Join-Path $svgPublishDir 'Jenin.FontAwesome.Blazor.Svg.dll')).Length
    Write-Host ("Trimmed {0} sizes: IconPicker={1:N0} bytes, Icons={2:N0} bytes, Svg={3:N0} bytes" -f $tfm, $iconPickerDll, $iconsDll, $svgDll) -ForegroundColor Green
}

Remove-Item -Recurse -Force -Path $probeRoot
Write-Host 'Optional-package trimming verification PASSED.' -ForegroundColor Green
