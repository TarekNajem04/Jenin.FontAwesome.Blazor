#!/usr/bin/env python3
"""Generate the self-contained inline-SVG icon components.

Reads the checked-in Free metadata, the vendored all.css (unicode map), and the vendored
WOFF2 fonts, and emits one sealed Blazor component per (icon, style) pair with the glyph
path inlined. Output is deterministic: sorted classes, invariant float formatting, CRLF
line endings with BOM, single trailing newline.

Requires: pip install fonttools

Usage: python eng/fa_svg_components.py
       python eng/fa_svg_components.py --check   # fail if the committed file differs
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ICON_BLOCK_RE = re.compile(
    r"(?m)^(?P<selectors>(?:\.fa-[a-z0-9-]+(?:\s*,\s*)?)+)\s*\{\s*\n"
    r'\s*--fa:\s*"(?P<escape>\\?[^"]+)";\s*\n\}',
)

STYLE_FONTS = {
    "solid": "fa-solid-900.woff2",
    "regular": "fa-regular-400.woff2",
    "brands": "fa-brands-400.woff2",
}

STYLE_SUFFIX = {"solid": "Solid", "regular": "Regular", "brands": "Brands"}

HEADER = """//
// Copyright (c) Jeninnet.
// Part of the Jeninnet Platform.
// Repository: https://github.com/TarekNajem04/Jenin.FontAwesome.Blazor/
// Licensed under the MIT License.
//
"""

AUTOGEN = """// <auto-generated>
//   Generated by eng/fa_svg_components.py from the vendored Font Awesome Free 7.3.1 assets
//   (WOFF2 glyph outlines, all.css unicodes, metadata names). Do not edit this file by hand.
//   Regenerate with: python eng/fa_svg_components.py
// </auto-generated>
"""


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate inline-SVG icon components.")
    parser.add_argument("--check", action="store_true", help="Fail when the committed file differs.")
    parser.add_argument("--out", type=Path, default=REPO / "src/Jenin.FontAwesome.Blazor.Svg/GeneratedIconComponents.cs")
    return parser.parse_args()


def decode_escape(escape: str) -> int:
    body = escape.strip()
    if body.startswith("\\"):
        body = body[1:].rstrip()
        if body and all(ch in "0123456789abcdefABCDEF" for ch in body):
            return int(body, 16)
    if body:
        return ord(body[0])
    raise ValueError(f"Cannot decode CSS escape: {escape!r}")


def to_class_name(name: str) -> str:
    parts = re.split(r"[-_]", name)
    out: list[str] = []
    for part in parts:
        if not part:
            continue
        out.append(part[0].upper() + part[1:])
    identifier = "".join(out)
    if identifier and identifier[0].isdigit():
        identifier = "_" + identifier
    return identifier


def xml_escape(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def round_path(path: str) -> str:
    """Round all coordinates to 2 decimals (visually identical, smaller + stable output)."""

    def shorten(match: re.Match[str]) -> str:
        text = f"{round(float(match.group(0)), 2):.2f}".rstrip("0").rstrip(".")
        return "0" if text == "-0" else text

    return re.sub(r"-?\d+\.\d+", shorten, path)


def load_glyph_map() -> dict[str, str]:
    """Return ({style:name -> path d}, {name -> [styles]})."""
    from fontTools.misc.transform import Transform
    from fontTools.pens.boundsPen import BoundsPen
    from fontTools.pens.svgPathPen import SVGPathPen
    from fontTools.pens.transformPen import TransformPen
    from fontTools.ttLib import TTFont

    css = (REPO / "samples/Jenin.FontAwesome.Blazor.Sample.Shared/wwwroot/fontawesome/css/all.css").read_text(encoding="utf-8")
    unicodes: dict[str, int] = {}
    for m in ICON_BLOCK_RE.finditer(css):
        for s in m.group("selectors").split(","):
            s = s.strip()
            if s.startswith(".fa-"):
                unicodes[s[4:]] = decode_escape(m.group("escape"))

    meta = json.loads((REPO / "eng/metadata/fontawesome-7.3.1-free-icon-metadata.json").read_text(encoding="utf-8"))
    fonts_dir = REPO / "samples/Jenin.FontAwesome.Blazor.Sample.Shared/wwwroot/fontawesome/webfonts"
    result: dict[str, str] = {}
    for icon in meta["icons"]:
        name = icon["name"]
        cp = unicodes.get(name)
        if cp is None:
            continue
        for style in icon.get("styles", []):
            font_file = STYLE_FONTS.get(style)
            if font_file is None:
                continue
            font = TTFont(str(fonts_dir / font_file))
            cmap = font.getBestCmap()
            if cp not in cmap:
                continue
            gs = font.getGlyphSet()
            glyph = gs[cmap[cp]]
            bp = BoundsPen(gs)
            glyph.draw(bp)
            if not bp.bounds:
                continue
            x0, y_min, x1, y_max = bp.bounds
            w, h = x1 - x0, y_max - y_min
            if w <= 0 or h <= 0:
                continue
            scale = min(512.0 / w, 512.0 / h)
            tx = (512.0 - scale * w) / 2 - scale * x0
            ty = (512.0 - scale * h) / 2 + scale * y_max
            pen = SVGPathPen(gs)
            glyph.draw(TransformPen(pen, Transform(scale, 0, 0, -scale, tx, ty)))
            result[f"{style}/{name}"] = round_path(pen.getCommands())
    return result


def build_content(paths: dict[str, str]) -> str:
    header = HEADER.replace("\n", "\r\n").rstrip("\r\n")
    autogen = AUTOGEN.replace("\n", "\r\n").rstrip("\r\n")
    lines = [header, "", autogen, "", "namespace Jenin.FontAwesome.Blazor.Svg;", ""]
    lines.append("// Per-icon inline-SVG components for the Font Awesome Free catalogue. Each component")
    lines.append("// renders one glyph as a self-contained <svg> with no Font Awesome JavaScript, CSS, or")
    lines.append("// webfonts. Unused components are linker-trimmed like any other unreferenced type.")
    lines.append("")
    for key in sorted(paths):
        style, name = key.split("/", 1)
        label = xml_escape(name.replace("-", " "))
        class_name = to_class_name(name) + STYLE_SUFFIX[style] + "Icon"
        lines.append(f'/// <summary>The Font Awesome <c>fa-{name}</c> {style} icon as inline SVG ({label}).</summary>')
        lines.append(f"public sealed class {class_name} : SvgIcon {{")
        lines.append(f'    /// <summary>Gets the SVG path data for the <c>fa-{name}</c> {style} icon.</summary>')
        lines.append(f'    protected override string PathData => "{paths[key]}";')
        lines.append("}")
        lines.append("")
    return "\r\n".join(lines)


def main() -> int:
    args = parse_args()
    paths = load_glyph_map()
    content = build_content(paths)
    if not content.endswith("\r\n"):
        content += "\r\n"
    data = content.encode("utf-8-sig")
    if args.check:
        if not args.out.exists():
            print(f"Missing generated inline-SVG components: {args.out}")
            return 1
        if args.out.read_bytes() != data:
            print("The generated inline-SVG components are out of date. Run: python eng/fa_svg_components.py")
            return 1
        print(f"Inline-SVG components are up to date ({len(paths)} glyphs).")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(data)
    print(f"Wrote {args.out} ({len(paths)} glyphs).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
